export type SnapshotResult = {
  status: "match" | "mismatch" | "created" | "updated";
  /** A coloured unified diff, present only on mismatch. */
  diff?: string;
};

/**
 * The output under test. In a real project this would be a rendered email,
 * a generated config file, a CLI's help text. Here it is a small report that
 * differs from the stored snapshot on purpose: one number changed and one
 * line was added.
 */
export const currentReport = (): string =>
  [
    "Sales report: Q3 2026",
    "=====================",
    "",
    "Region        Orders    Revenue",
    "------------  ------  ---------",
    "North             42   12,480.00",
    "South             37   10,915.50",
    "East              61   18,104.25",
    "West              29    8,330.00",
    "------------  ------  ---------",
    "Total            169   49,829.75",
    "",
    "Top product: Widget Pro (61 units)",
    "Returns: 4 (2.4%)",
    "Refunds: 1 (0.6%)",
    "Generated by sales-reporter v1.2",
    "",
  ].join("\n");

/**
 * The snapshot diff challenge.
 *
 * Snapshot testing stores a known-good copy of some output and fails when
 * the output changes, showing exactly what changed. Implement the core of
 * it.
 *
 * The snapshot for `name` lives at `<dir>/<name>.txt`.
 *   - If that file does not exist, write `actual` to it and return
 *     `{ status: "created" }`.
 *   - If `update` is true, overwrite it and return `{ status: "updated" }`.
 *   - Otherwise read it and compare with `actual`. Equal text returns
 *     `{ status: "match" }`. Different text returns `{ status: "mismatch",
 *     diff }` where `diff` is a unified diff produced by
 *     `createTwoFilesPatch` from ./init, with each removed line coloured red
 *     and each added line green using `styleText` from `node:util`. Leave
 *     the `---`, `+++` and `@@` header lines uncoloured.
 *
 * Use `node:fs/promises`. Treat a missing file (`ENOENT`) as "create"; let
 * any other error propagate.
 *
 * Example (snapshot says "East 58", actual says "East 61"):
 *   checkSnapshot("report", actual, dir, false) -> {
 *     status: "mismatch",
 *     diff: "...\n-East  58\n+East  61\n...",   // with ANSI colours
 *   }
 *
 * @param name The snapshot name.
 * @param actual The current output to compare.
 * @param dir The directory holding snapshot files.
 * @param update Whether to overwrite the snapshot instead of comparing.
 */
const checkSnapshot = async (
  name: string,
  actual: string,
  dir: string,
  update: boolean,
): Promise<SnapshotResult> => {
  return { status: "match" };
};

export const main = async (name: string, dir: string, update: boolean) => {
  console.log("Snapshot:", `${name}.txt`, "in", dir);
  if (update) {
    console.log(
      "(--update rewrites the committed fixture; `git checkout` restores it)",
    );
  }
  const result = await checkSnapshot(name, currentReport(), dir, update);
  console.log("Status:", result.status);
  if (result.status === "mismatch") {
    console.log(`\n${result.diff ?? "(no diff produced)"}`);
    process.exitCode = 1;
  }
};
